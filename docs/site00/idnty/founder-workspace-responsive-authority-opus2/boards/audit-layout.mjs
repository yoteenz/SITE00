#!/usr/bin/env node
/**
 * Automated responsive layout audit (Opus 2). Loads every specimen state at the 16 sprint viewports in Chromium
 * and measures, in the live DOM:
 *   overflow     page or stage wider than its viewport; text boxes outside the viewport
 *   collision    two visible text boxes in the same layer overlapping (> 4 px²)
 *   dimensions   visible text elements with zero or invalid size
 *   inspector    inspector wider than the viewport, or docked while the stage is < 680 px
 *   truncation   mandatory labels (labels, tabs, buttons, status, chips, headers, nav) clipped by ellipsis
 *   multiline    buttons whose label wraps to more than one line
 *   min-text     computed font size below 10 px
 *   fonts        any text not rendered in a loaded SITE 00 Display / Saira Semi Condensed face
 *   stretch      gaps wider than 360 px between neighbouring text inside one row component (warning)
 * Writes ../verification/layout-audit.json, layout-audit-summary.md and contact sheets.
 *
 * Usage (repo root): node docs/site00/idnty/founder-workspace-responsive-authority-opus2/boards/audit-layout.mjs [--no-sheets]
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { here, start, SPECIMEN, VIEWPORTS, tierOf, measure } from './lib.mjs';

const STATES = [
  'page=overview', 'page=overview&st=empty', 'page=overview&st=error-detail',
  'page=foundations', 'page=foundations&sel=0&insp=client', 'page=foundations&st=search', 'page=foundations&st=empty',
  'page=record', 'page=record&sec=1', 'page=record&sec=2', 'page=record&sec=3',
  'page=reviews', 'page=reviews&detail=1', 'page=reviews&state=revise',
  'page=operations', 'page=operations&insp=task',
  'page=correspondence', 'page=correspondence&detail=1', 'page=lifecycle', 'page=lifecycle&insp=email',
  'page=system', 'page=system&insp=module', 'page=testlab', 'page=components',
  ...['OL-01', 'OL-02', 'OL-03', 'OL-04', 'OL-05', 'OL-06', 'OL-07', 'OL-08', 'OL-09', 'OL-10', 'OL-11', 'OL-13', 'OL-14', 'OL-15', 'OL-17', 'OL-18', 'OL-19', 'OL-20', 'TOAST'].map((k) => `ol=${k}`),
  'ol=OL-01&os=error', 'ol=OL-01&os=failed',
];
const SHEETS = ['page=overview', 'page=foundations', 'page=foundations&sel=0&insp=client', 'page=record', 'page=reviews', 'page=reviews&detail=1', 'page=operations', 'page=correspondence', 'page=system', 'page=testlab', 'ol=OL-01', 'ol=OL-04', 'ol=OL-06'];

const sheets = !process.argv.includes('--no-sheets');
const outDir = join(here, '..', 'verification');
const sheetDir = join(outDir, 'contact-sheets');
mkdirSync(sheetDir, { recursive: true });
const { base, data, browser, close } = await start(5247);
const results = [];
const shots = {};
try {
  for (const [w, h] of VIEWPORTS) {
    const page = await browser.newPage({ viewport: { width: w, height: h }, deviceScaleFactor: 1 });
    await page.addInitScript(`window.__DF = ${JSON.stringify(data)};`);
    for (const q of STATES) {
      const errors = [];
      const onErr = (e) => errors.push(String(e));
      page.on('pageerror', onErr);
      await page.goto(`${base}/${SPECIMEN}?${q}`, { waitUntil: 'networkidle' });
      await page.waitForFunction(() => document.body.dataset.ready === '1', null, { timeout: 20000 }).catch(() => errors.push('not ready'));
      const m = await page.evaluate(measure);
      page.off('pageerror', onErr);
      const fails = ['overflow', 'collision', 'dimensions', 'inspector', 'truncation', 'multiline', 'minText', 'fonts'].reduce((s, k) => s + m[k].length, 0) + errors.length;
      results.push({ state: q, viewport: `${w}x${h}`, tier: tierOf(w), pass: fails === 0, warnings: m.stretch.length, errors, ...m });
      if (sheets && SHEETS.includes(q)) {
        const buf = await page.screenshot({ type: 'jpeg', quality: 70 });
        (shots[q] ??= []).push({ w, h, buf: buf.toString('base64') });
      }
    }
    await page.close();
    console.log(`viewport ${w}×${h} done`);
  }
} finally {
  await close();
}

const total = results.length;
const passed = results.filter((r) => r.pass).length;
writeFileSync(join(outDir, 'layout-audit.json'), `${JSON.stringify({ generated_by: 'boards/audit-layout.mjs', browser: 'Playwright Chromium (bundled)', viewports: VIEWPORTS.map(([w, h]) => `${w}x${h}`), states: STATES, total, passed, results }, null, 2)}\n`);

const keys = ['overflow', 'collision', 'dimensions', 'inspector', 'truncation', 'multiline', 'minText', 'fonts', 'stretch'];
const sums = Object.fromEntries(keys.map((k) => [k, results.reduce((s, r) => s + (r[k].length ? 1 : 0), 0)]));
let md = `# Layout audit summary\n\nGenerated by \`boards/audit-layout.mjs\` in Playwright Chromium. ${STATES.length} specimen states × ${VIEWPORTS.length} viewports = **${total} renders**, **${passed} passed** every hard check.\n\n`;
md += `| Check | Renders with a finding |\n| --- | --- |\n${keys.map((k) => `| ${k}${k === 'stretch' ? ' (warning)' : ''} | ${sums[k]} |`).join('\n')}\n\n`;
const failing = results.filter((r) => !r.pass);
md += failing.length ? `## Failing renders\n\n| State | Viewport | Findings |\n| --- | --- | --- |\n${failing.map((r) => `| \`${r.state}\` | ${r.viewport} | ${keys.filter((k) => r[k].length && k !== 'stretch').map((k) => `${k}: ${r[k].slice(0, 2).join('; ').replace(/\|/g, '/')}`).join(' · ')}${r.errors.length ? ` · errors: ${r.errors.join('; ')}` : ''} |`).join('\n')}\n` : '## Failing renders\n\nNone.\n';
const warn = results.filter((r) => r.stretch.length);
md += `\n## Stretch-gap warnings\n\n${warn.length ? warn.map((r) => `- \`${r.state}\` @ ${r.viewport}: ${r.stretch.slice(0, 2).join('; ')}`).join('\n') : 'None.'}\n`;
writeFileSync(join(outDir, 'layout-audit-summary.md'), md);
writeFileSync(join(outDir, 'contact-sheets', 'shots.json'), JSON.stringify(Object.fromEntries(Object.entries(shots).map(([q, s]) => [q, s.map(({ w, h }) => [w, h])]))));
if (sheets) for (const [q, list] of Object.entries(shots)) for (const s of list) writeFileSync(join(sheetDir, `_${q.replace(/[^a-z0-9]+/gi, '_')}__${s.w}x${s.h}.jpg`), Buffer.from(s.buf, 'base64'));
console.log(`audit: ${passed}/${total} renders pass · ${Object.entries(sums).map(([k, v]) => `${k} ${v}`).join(' · ')}`);
