#!/usr/bin/env python3
"""Advance widths for correspondence text measurement in the email generator.

Usage:
  python3 scripts/correspondence-studio/editorial/extract_font_metrics.py

Reads the shipped webfonts and the Arial-metric fallback (Liberation Sans is metric-compatible with
Arial, the last named family in every FNDATN-01 font stack). Email clients that refuse webfonts
(Gmail, Outlook desktop) render the fallback, so the generator measures every string against the
wider of the two per glyph. Writes
shared/site00-correspondence-studio/editorial/fontMetrics.generated.ts
"""
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[3]
FONTS = ROOT / 'public/site00-correspondence-studio/fndatn-01/fonts'
LIBERATION = Path('/usr/share/fonts/truetype/liberation')
OUT = ROOT / 'shared/site00-correspondence-studio/editorial/fontMetrics.generated.ts'

CHARS = [chr(c) for c in range(32, 127)] + list('·×→’‘“”–—€£¥')

SOURCES = {
    'saira400': FONTS / 'saira-semi-condensed-latin-400.woff2',
    'saira500': FONTS / 'saira-semi-condensed-latin-500.woff2',
    'saira600': FONTS / 'saira-semi-condensed-latin-600.woff2',
    'display': FONTS / 'site00-correspondence-display.woff2',
    'arial400': LIBERATION / 'LiberationSans-Regular.ttf',
    'arial700': LIBERATION / 'LiberationSans-Bold.ttf',
}


def widths(path):
    font = TTFont(str(path))
    upm = font['head'].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font['hmtx']
    out = {}
    for ch in CHARS:
        gid = cmap.get(ord(ch))
        if gid is None:
            continue
        out[ch] = round(hmtx[gid][0] / upm, 4)
    return out


def main():
    tables = {k: widths(p) for k, p in SOURCES.items()}
    lines = [
        '/* Generated by scripts/correspondence-studio/editorial/extract_font_metrics.py. Do not edit. */',
        '/** Advance widths in em per character. Arial columns are Liberation Sans (Arial-metric compatible). */',
        'export const FONT_ADVANCE_EM = {',
    ]
    for key, table in tables.items():
        body = ','.join(f'{repr(ch) if ch != chr(92) else repr(chr(92))}:{w}' for ch, w in table.items())
        lines.append(f'  {key}: {{{body}}} as Record<string, number>,')
    lines.append('} as const;')
    lines.append('')
    lines.append('export type FontMetricKey = keyof typeof FONT_ADVANCE_EM;')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines) + '\n')
    for k, t in tables.items():
        print(f'{k:9s} glyphs={len(t):3d}  avg A-Z={sum(t.get(c, 0) for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ") / 26:.3f}em')
    print(f'wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
