/** The section 11 fields for one promoted proposal, as a labelled block (phone-readable). */
export function promotionBlock(p: X.Promotion.PromotionRecord): string {
  const deps = p.dependencies.length ? p.dependencies.map((d) => `${d.kind} ${d.to}: ${d.resolution}`) : ['None.'];
  const impl = p.implementation;
  const where = [
    impl.masterAmendments.length && `master amendments ${impl.masterAmendments.join(', ')}`,
    impl.worldRules.length && `season rules ${impl.worldRules.join(', ')}`,
    impl.soundMotifs.length && `sound motifs ${impl.soundMotifs.join(', ')}`,
    impl.backgroundIdentities.length && `background identities ${impl.backgroundIdentities.join(', ')}`,
    impl.s101Patch.length && `S1-01 patch ${impl.s101Patch.join(', ')} (proposed, not applied)`,
  ].filter(Boolean);
  return [
    `### ${p.order}. ${p.proposalId} — ${p.title}`,
    '',
    `- **Proposal ID:** ${p.proposalId} (${p.type}, category ${p.category}; audit recommendation ${p.auditRecommendation})`,
    `- **Founder approval:** ${p.founderApproval}. Decision state ${p.decisionState}.`,
    `- **Affected releases:** ${p.affectedReleases.join(', ')}`,
    `- **Affected beats:** ${p.affectedBeats.join('; ')}`,
    `- **Original behaviour:** ${p.originalBehavior}`,
    `- **Approved behaviour:** ${p.approvedBehavior}`,
    `- **Runtime impact:** ${p.runtimeImpactSec} s`,
    `- **Continuity implications:** ${p.continuityImplications.join(' ') || 'None recorded.'}`,
    `- **Asset implications:** ${p.assetImplications.join('; ') || 'None.'}`,
    `- **Production hold status:** ${p.productionState} (${p.productionHolds.length ? p.productionHolds.join(', ') : 'no hold'})`,
    `- **Implemented in:** ${where.join('; ') || 'nothing'}`,
    `- **Dependencies:** ${deps.join(' ')}`,
    '- **Source evidence:**',
    ...p.sourceEvidence.map((e) => `  - ${e.ref}${e.file.endsWith('MASTER_V1.json') ? '' : ` (${path.basename(e.file)})`}: "${e.quote}"`),
  ].join('\n');
}
