import fs from 'node:fs';
import path from 'node:path';

export const DOCS_DIR = 'docs/site00/the-exchange/founder-canon-lock-v1';

type Cell = string | number | boolean | null | undefined;

const cell = (v: Cell) => (v === null || v === undefined || v === '' ? '—' : String(v).replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>'));

export function table(header: string[], rows: Cell[][]): string {
  return [`| ${header.join(' | ')} |`, `| ${header.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
}

export const bullets = (items: Cell[]) => (items.length ? items.map((i) => `- ${cell(i).replace(/<br>/g, ' ')}`).join('\n') : '- None');

export function generatedNote(sources: string[]): string {
  return `> Generated by \`scripts/the-exchange/render-canon-lock-docs.ts\` from ${sources.map((s) => `\`${s}\``).join(', ')}. Regenerate instead of editing by hand.`;
}

export function writeDoc(root: string, name: string, body: string): void {
  const file = path.join(root, DOCS_DIR, name);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body.endsWith('\n') ? body : `${body}\n`);
  console.log(`wrote ${DOCS_DIR}/${name}`);
}

export const secs = (s: number) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`;
