import fs from 'node:fs';
import * as X from '../../../shared/site00-fiction-production/index.js';

/** Deliverables 03 and 04 of the S1-01 packet alignment, rendered from the patch record, the live packet and the audited packet view. */
export const S101_ALIGNMENT_DOCS_DIR = 'docs/site00/production-spine-and-s101-alignment-v1';
const SPRINT = 'P0.SITE00.STUDIOWORLD.PRODUCTION-SPINE-AND-EXCHANGE-S101-PACKET-ALIGNMENT.V1';
const PACKET = 'THE_EXCHANGE/SEASON_1/PRODUCTION_SCENES/S1-01/DIRECTORIAL_PACKET_V1.json';
const AUDITED = 'scripts/the-exchange/living-world-audit/S1-01_PACKET_AT_AUDIT.json';

type Decision = { decisionId: string; question: string; status: string; answer?: string | null; note?: string; progress?: string[] };
type Person = { personId: string; name: string; tier: string };
type PacketView = {
  status: string;
  sections: {
    '1_SCENE_OVERVIEW': { estimatedDuration: string };
    '4_SHOT_STORYBOARD': { shots: Array<{ shotId: string }>; counts: { total: number } };
    '6_CHARACTERS_AND_ASSETS': { cast: { people: Person[]; rule?: string }; forwardReferences?: { note: string; references: X.Directorial.ForwardReference[] } };
    '7_MUSIC_AND_SOUND': { summary: { musicCues: number; silenceCues: number; soundCues: number } };
    '9_FOUNDER_DECISIONS': Decision[];
  };
};

const cell = (v: unknown) => String(v ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (head: string[], rows: unknown[][]) => [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
const head = (n: string, title: string, sources: string[]) => [
  `# ${n} — ${title}`,
  '',
  `> Generated by \`scripts/the-exchange/render-s101-alignment.ts\` from ${sources.map((s) => `\`${s}\``).join(', ')}. Regenerate instead of editing by hand.`,
  '',
  `Sprint \`${SPRINT}\`. The founder authorized PATCH-S101-01 to -07 (§03 A). No media was generated, no provider was called and no credit was spent.`,
  '',
];

function sevenPatchDiff(root: string): string {
  const P = X.Promotion;
  const baseline = new Map(X.Audit.PROTECTED_BASELINE.map((f) => [f.path, f.sha256]));
  const moved = Object.entries(X.Audit.FOUNDER_S101_PATCH_BASELINE);
  return [
    ...head('03', 'S1-01 seven-patch diff', ['shared/site00-fiction-production/promotion/s101Patch.ts', 'shared/site00-fiction-production/audit/baseline.ts']),
    `${P.S101_PATCH.length} patch items, all ${[...new Set(P.S101_PATCH.map((x) => x.status))].join(', ')}. Each "before" is quoted from the packet the founder reviewed; each "after" is the contract from Living World Promotion V1 deliverable 08; "present" and "absent" are the exact packet strings the validator now checks.`,
    '',
    '## 1. Files the patch moved',
    '',
    table(['File', 'Audit sha256', 'Founder-authorized sha256'], moved.map(([path, sha]) => [`\`${path}\``, `\`${baseline.get(path)?.slice(0, 16)}…\``, `\`${sha.slice(0, 16)}…\``])),
    '',
    'Unchanged by the patch: the cue sheet, multitrack, budget and review state of S1-01, the five Fountain drafts, the season master, the cast registry and the approval book.',
    '',
    '## 2. Patch items',
    '',
    ...P.S101_PATCH.flatMap((x) => [
      `### ${x.patchId}. ${x.subject}`,
      '',
      `- **Authority:** ${x.authority.join('; ')}`,
      `- **Source modules:** ${[...new Set(x.targets.map((t) => `\`${t.sourceModule}\``))].join(', ')}`,
      `- **Affects:** ${x.affects.join(', ')}`,
      `- **Status:** ${x.status}${x.applied ? ` (${x.applied.date})` : ''}`,
      '- **Before:**',
      ...(x.before.length ? x.before.map((b) => `  - "${b}"`) : ['  - Nothing: a new note.']),
      '- **After (contract):**',
      ...x.after.map((a) => `  - ${a}`),
      '- **Present in the packet now:**',
      ...(x.applied?.present ?? []).map((t) => `  - "${t}"`),
      '- **Gone from the packet:**',
      ...((x.applied?.absent ?? []).length ? x.applied!.absent.map((t) => `  - "${t}"`) : ['  - Nothing replaced.']),
      ...(x.applied?.note ? [`- **Implementation note:** ${x.applied.note}`] : []),
      `- **Unchanged:** ${x.unchanged}`,
      '',
    ]),
    '## 3. Decisions the patch did not take',
    '',
    `- Still open: ${P.S101_GUARDS.stillOpen.join(', ')}.`,
    `- Opened by the patch: ${P.S101_GUARDS.addedByPatch.join(', ')} (the four-count step, CHOREOGRAPHY_LOCK_PENDING).`,
    '- No screenplay approval (FD-S101-01), city reference (FD-S101-08) or generation budget (FD-S101-11) is recorded.',
    '',
  ].join('\n');
}

function packetValidation(root: string): string {
  const read = (rel: string) => fs.readFileSync(X.repoPath(rel, root), 'utf8');
  const before = JSON.parse(read(AUDITED)) as PacketView;
  const after = JSON.parse(read(PACKET)) as PacketView;
  const plan = X.directedSceneBundle('S1-01', root).direction.plan;
  const master = X.loadSeasonMaster(root);
  const b = before.sections;
  const a = after.sections;
  const status = (v: PacketView) => (id: string) => v.sections['9_FOUNDER_DECISIONS'].find((d) => d.decisionId === id)?.status ?? '—';
  const decisionIds = [...new Set([...b['9_FOUNDER_DECISIONS'], ...a['9_FOUNDER_DECISIONS']].map((d) => d.decisionId))];
  const tier = (v: PacketView) => (id: string) => v.sections['6_CHARACTERS_AND_ASSETS'].cast.people.find((p) => p.personId === id)?.tier ?? '—';
  const people = a['6_CHARACTERS_AND_ASSETS'].cast.people.map((p) => p.personId);
  const promotion = X.Promotion.validatePromotion(root);
  const audit = X.Audit.validateAudit(root);
  const pass = (c: { errors: string[] }) => (c.errors.length ? `FAIL (${c.errors.length})` : 'PASS');
  const kf = (id: string) => plan.keyframes.find((k) => k.keyframeId === id)!;
  const fwd = a['6_CHARACTERS_AND_ASSETS'].forwardReferences;
  return [
    ...head('04', 'S1-01 directorial packet validation', [AUDITED, PACKET, 'shared/site00-fiction-production/promotion/validate.ts', 'shared/site00-fiction-production/audit/validate.ts']),
    '"Before" is the packet the Living World Audit read (sha256 at the audit baseline); "after" is the rebuilt packet.',
    '',
    '## 1. Protected baseline',
    '',
    table(['Measure', 'Before', 'After', 'Result'], [
      ['Runtime', b['1_SCENE_OVERVIEW'].estimatedDuration, a['1_SCENE_OVERVIEW'].estimatedDuration, b['1_SCENE_OVERVIEW'].estimatedDuration === a['1_SCENE_OVERVIEW'].estimatedDuration ? 'UNCHANGED' : 'CHANGED'],
      ['Frames at 24 fps', 1080, plan.durationFrames, plan.durationFrames === 1080 && plan.fps === 24 ? 'UNCHANGED' : 'CHANGED'],
      ['Shots', b['4_SHOT_STORYBOARD'].shots.length, a['4_SHOT_STORYBOARD'].shots.length, b['4_SHOT_STORYBOARD'].shots.map((s) => s.shotId).join() === a['4_SHOT_STORYBOARD'].shots.map((s) => s.shotId).join() ? 'UNCHANGED (same order)' : 'CHANGED'],
      ['Keyframe requirements', b['4_SHOT_STORYBOARD'].counts.total, a['4_SHOT_STORYBOARD'].counts.total, b['4_SHOT_STORYBOARD'].counts.total === a['4_SHOT_STORYBOARD'].counts.total ? 'UNCHANGED' : 'CHANGED'],
      ['Music cues', b['7_MUSIC_AND_SOUND'].summary.musicCues, a['7_MUSIC_AND_SOUND'].summary.musicCues, b['7_MUSIC_AND_SOUND'].summary.musicCues === a['7_MUSIC_AND_SOUND'].summary.musicCues ? 'UNCHANGED' : 'CHANGED'],
      ['Silences', b['7_MUSIC_AND_SOUND'].summary.silenceCues, a['7_MUSIC_AND_SOUND'].summary.silenceCues, b['7_MUSIC_AND_SOUND'].summary.silenceCues === a['7_MUSIC_AND_SOUND'].summary.silenceCues ? 'UNCHANGED' : 'CHANGED'],
      ['Sound cues', b['7_MUSIC_AND_SOUND'].summary.soundCues, a['7_MUSIC_AND_SOUND'].summary.soundCues, b['7_MUSIC_AND_SOUND'].summary.soundCues === a['7_MUSIC_AND_SOUND'].summary.soundCues ? 'UNCHANGED' : 'CHANGED'],
      ['Dialogue lines', 0, plan.dialogue.length, plan.dialogue.length === 0 ? 'UNCHANGED (wordless)' : 'CHANGED'],
      ['Packet status', before.status, after.status, `Screenplay still ${plan.screenplay.status}`],
      ['Season releases', 86, master.releases.length, master.releases.length === 86 ? 'UNCHANGED' : 'CHANGED'],
      ['Season runtime', '127:40 (7,660 s)', `${master.structure.runtimeTotalSec} s`, master.structure.runtimeTotalSec === 7660 ? 'UNCHANGED' : 'CHANGED'],
    ]),
    '',
    '## 2. Founder decisions',
    '',
    table(['Decision', 'Before', 'After', 'Progress'], decisionIds.map((id) => [id, status(before)(id), status(after)(id), a['9_FOUNDER_DECISIONS'].find((d) => d.decisionId === id)?.progress?.join(', ') ?? ''])),
    '',
    '## 3. Cast tiers',
    '',
    table(['Person', 'Before', 'After'], people.map((id) => [`\`${id}\``, tier(before)(id), tier(after)(id)])),
    '',
    `Cast rule now: "${a['6_CHARACTERS_AND_ASSETS'].cast.rule}"`,
    '',
    '## 4. Approval dependencies',
    '',
    table(['Keyframe', 'Blocked by', 'Reusable beyond S1-01'], ['KF-SF-SH02', 'KF-SF-SH05', 'KF-SF-SH10', 'KF-WD-GREEN-DRESS'].map((id) => [id, kf(id).blockedBy.join(', ') || '— (inherits upstream blocks)', kf(id).reusableBeyondUnit.join('; ') || '—'])),
    '',
    `KF-SF-SH06 derives from KF-SF-SH05 and KF-SF-SH07 is extracted from the SH05 take, so FD-S101-12 holds all three teenager shots. Keyframe counts: ${JSON.stringify(X.Directorial.keyframeCounts(plan))}.`,
    '',
    '## 5. Forward references',
    '',
    fwd ? fwd.note : 'Missing.',
    '',
    table(['Who', 'Release', 'Proposal', 'Appearance', 'Reuses'], (fwd?.references ?? []).map((r) => [r.subject, r.releaseId, r.proposalId, r.appearance, r.reuses.join(', ')])),
    '',
    '## 6. Validators',
    '',
    table(['Check', 'Result', 'Checked'], [...promotion.map((c) => [`promotion ${c.id}`, pass(c), c.checked]), ...audit.map((c) => [`audit ${c.id}`, pass(c), c.checked])]),
    '',
    `Packet validation: ${(after as unknown as { validation: { errors: number; warnings: number; advisories: number } }).validation.errors} errors, ${(after as unknown as { validation: { warnings: number } }).validation.warnings} warnings, ${(after as unknown as { validation: { advisories: number } }).validation.advisories} advisories.`,
    '',
  ].join('\n');
}

export function buildS101AlignmentDocs(root: string): Record<string, string> {
  return { '03_S101_SEVEN_PATCH_DIFF.md': sevenPatchDiff(root), '04_S101_DIRECTORIAL_PACKET_VALIDATION.md': packetValidation(root) };
}
