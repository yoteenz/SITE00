/** Everything the doc builders read, loaded once. */
export type Ctx = {
  root: string;
  master: X.SeasonMaster;
  index: X.SceneIndex;
  ledger: {
    facts: Array<{ factId: string; statement: string; classification: string; writersRoom: string; audienceFrom: string | null; knownBy: Array<{ character: string; from: string; how: string }> }>;
    openQuestions: Array<{ id: string; question: string; status: string; appliesTo: string }>;
  };
  packet: {
    status: string;
    shots: Array<{ shotId: string; sceneId: string; subject: string; intendedScreenTime: number }>;
    keyframes: number;
    music: { musicCues: number; silenceCues: number; soundCues: number };
    duration: string;
    decisions: Array<{ decisionId: string; question: string; recommendation: string; status: string }>;
    people: Array<{ personId: string; name: string; tier: string }>;
  };
  checks: X.Audit.AuditCheck[];
  rel: Map<string, X.MasterRelease>;
  brief: Map<string, X.ReleaseBrief>;
  byId: Map<string, Proposal>;
  placedIn: (releaseId: string) => Proposal[];
};

export function loadCtx(root: string): Ctx {
  const read = (rel: string) => fs.readFileSync(X.repoPath(rel, root), 'utf8');
  const master = X.loadSeasonMaster(root);
  const index = JSON.parse(read(A.SCENE_INDEX)) as X.SceneIndex;
  const raw = JSON.parse(read(A.S101_PACKET)) as {
    status: string;
    sections: {
      '1_SCENE_OVERVIEW': { estimatedDuration: string };
      '4_SHOT_STORYBOARD': { shots: Ctx['packet']['shots']; counts: { total: number } };
      '6_CHARACTERS_AND_ASSETS': { cast: { people: Ctx['packet']['people'] } };
      '7_MUSIC_AND_SOUND': { summary: Ctx['packet']['music'] };
      '9_FOUNDER_DECISIONS': Ctx['packet']['decisions'];
    };
  };
  const s = raw.sections;
  return {
    root,
    master,
    index,
    ledger: JSON.parse(read(X.EXCHANGE_PATHS.knowledge)) as Ctx['ledger'],
    packet: {
      status: raw.status,
      shots: s['4_SHOT_STORYBOARD'].shots,
      keyframes: s['4_SHOT_STORYBOARD'].counts.total,
      music: s['7_MUSIC_AND_SOUND'].summary,
      duration: s['1_SCENE_OVERVIEW'].estimatedDuration,
      decisions: s['9_FOUNDER_DECISIONS'],
      people: s['6_CHARACTERS_AND_ASSETS'].cast.people,
    },
    checks: A.validateAudit(root),
    rel: new Map(master.releases.map((r) => [r.id, r])),
    brief: new Map(index.releases.map((r) => [r.releaseId, r])),
    byId: new Map(A.PROPOSALS.map((p) => [p.id, p])),
    placedIn: (releaseId: string) => A.PROPOSALS.filter((p) => p.releases[0] === releaseId),
  };
}

