export function impactFlags(i: X.Audit.ProductionImpact | undefined): string {
  if (!i) return 'None (rejected or no production).';
  const flags = [
    i.newScene && 'new scene',
    i.newCharacterAsset && 'new character asset',
    i.newProp && 'new prop',
    i.newMusicOrSfx && 'new music or SFX',
    i.reusesLocation && `reuses ${i.reusesLocation}`,
    i.reusesCharacter && `reuses ${i.reusesCharacter}`,
  ].filter(Boolean);
  return flags.length ? flags.join('; ') : 'nothing new';
}

