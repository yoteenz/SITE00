export const DOCS_DIR = 'docs/site00/the-exchange/directorial-production-engine-v2';

export function generatedNote(sources: string[]): string {
  return `> Generated by \`scripts/the-exchange/render-directorial-docs.ts\` from ${sources.map((s) => `\`${s}\``).join(', ')}. Regenerate instead of editing by hand.`;
}

export function writeDoc(root: string, name: string, body: string): void {
  const file = path.join(root, DOCS_DIR, name);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body.endsWith('\n') ? body : `${body}\n`);
  console.log(`wrote ${DOCS_DIR}/${name}`);
}

