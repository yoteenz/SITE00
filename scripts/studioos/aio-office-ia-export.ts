function visibilityRows() {
  return IA.nodes.filter((x) => x.kind !== 'SHELL').map((x) => {
    const staffShell = x.shell_id === 'AIO_OFFICE';
    const proj = staffShell ? projectionOf(x) : null;
    return {
      node_id: x.node_id, path: at(x.node_id), kind: x.kind,
      FOUNDER: x.visibility.FOUNDER, STAFF: x.visibility.STAFF, CLIENT: x.visibility.CLIENT,
      firewall: firewalled.has(x.node_id),
      client_safe_projection: firewalled.has(x.node_id) ? null : proj,
      staff_reach: staffShell ? null : staffReach(x),
      client_resolution: x.client_resolution,
      staff_gate: x.staff_gate,
    };
  });
}

