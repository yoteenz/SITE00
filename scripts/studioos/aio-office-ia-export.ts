/** The nearest staff ancestor's approved client-safe projection. */
function projectionOf(x: IaNode): string | null {
  for (let c: IaNode | undefined = x; c; c = c.parent ? iaNode(IA, c.parent) : undefined) if (c.client_projection) return c.client_projection;
  return null;
}
/** How staff reach a client-office node's data from AIO OFFICE (never by entering the client shell). */
function staffReach(c: IaNode): string[] {
  for (let p: IaNode | undefined = c; p && p.kind !== 'SHELL'; p = p.parent ? iaNode(IA, p.parent) : undefined) {
    const direct = IA.nodes.filter((s) => s.client_projection === p!.node_id).map((s) => s.node_id);
    if (direct.length) return direct;
    const viaService = [...new Set(IA.services.filter((s) => p!.service_ids.includes(s.service_id)).flatMap((s) => s.staff_nodes))];
    if (viaService.length) return viaService;
  }
  return ['AIO_OFFICE.MORE.CLIENTS'];
}
