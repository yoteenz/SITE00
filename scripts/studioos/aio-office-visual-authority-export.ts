function approvalMd() {
  return [
    ...MD_HEAD('01 · Founder approval record'),
    `Fifteen decisions, decided by the FOUNDER on ${brain.AIO_VA_DATE}. Each one approves the reconciliation’s recommended option. The reconciliation package itself stays as delivered (its decisions were OPEN at delivery) — this record carries the approvals, so the lineage is kept.`, '',
    'Approving these decisions authorizes **design development only** — not live implementation, security changes, deployment, or automatic approval of the renders built on them.', '',
    table(['Decision', 'Question', 'Approved option', 'Approved as', 'Modification'], APPROVALS.map((a) => {
      const d = decision(a.decision_id);
      return [`${a.decision_id} — ${d.title}`, d.question, d.options[a.chosen_option].option, a.approved_as, a.modification ?? '—'];
    })), '',
  ].join('\n');
}

