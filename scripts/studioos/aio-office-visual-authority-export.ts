function framesMd() {
  return [
    ...MD_HEAD('03 · Visual authority frames'),
    `Thirty frames, ${brain.AIO_VA_RENDERS.length} PNG files in fsbw \`AIO_OFFICE_VISUAL_AUTHORITY/\`. Every one is a **CANDIDATE awaiting founder approval**, carries ILLUSTRATIVE SAMPLE DATA (labelled SAMPLE), and passed the automated visual QA read from the rendered DOM. A re-render reproduces every sha256.`, '',
    table(['#', 'Frame', 'Root', 'Viewport', 'Actor', 'Shows', 'Files (sha256)', 'QA'], brain.AIO_VA_FRAMES.map((f) => [
      String(f.deliverable), f.frame, f.root, f.viewport, f.actor, f.shows,
      rendersOf(f.frame).map((r) => `\`${r.file.split('/').pop()}\` ${r.sha256.slice(0, 12)}…`).join('<br>'),
      rendersOf(f.frame).every((r) => r.qa_pass) ? `PASS (${[...new Set(rendersOf(f.frame).flatMap((r) => r.qa_checks))].join(', ')})` : 'FAIL',
    ])), '',
  ].join('\n');
}

