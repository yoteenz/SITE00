export function buildAioVisualAuthorityExports(): Record<string, string> {
  return {
    'README.md': readmeMd(),
    '01_FOUNDER_APPROVAL_RECORD.md': approvalMd(),
    '02_AIO_OFFICE_CREATIVE_DIRECTION_PROFILE.md': profileMd(),
    '03_VISUAL_AUTHORITY_FRAMES.md': framesMd(),
    '04_APPROVED_ASSET_REUSE.md': assetsMd(),
    '05_MISSING_ASSETS.md': missingMd(),
    '06_COMPONENTS_AND_ICONS.md': componentsMd(),
    '07_ORIGINAL_VS_REVISED.md': comparisonMd(),
    '08_RESPONSIVE_AND_ULTRA_WIDE.md': responsiveMd(),
    '09_PERMISSIONS_AND_PRIVACY.md': permissionsMd(),
    '10_COMPOSER_HANDOFF_DRAFT.md': handoffMd(),
    'VISUAL_AUTHORITY.json': json({
      id: 'AIO_OFFICE_VISUAL_AUTHORITY', sprint: SPRINT, date: brain.AIO_VA_DATE, generated_by: 'scripts/studioos/aio-office-visual-authority-export.ts',
      source: ['shared/studioos-experience-brain/projects/aio/office-visual-authority.ts', 'shared/studioos-experience-brain/projects/aio/office-visual-authority-renders.ts', 'shared/studioos-visual-authority/projects/aio/office-creative-direction-profile.ts'],
      status: S, next_gate: brain.AIO_VA_NEXT_GATE, locations: brain.AIO_VA_LOCATIONS,
      reference: REC.reference.file,
      approvals: APPROVALS, profile: { scope: SCOPE, profile: PROFILE, check: checkCreativeDirectionProfile(PROFILE) },
      frames: brain.AIO_VA_FRAMES, renders: brain.AIO_VA_RENDERS,
      assets: { reused: brain.AIO_VA_ASSET_REUSE, created: brain.AIO_VA_NEW_ASSETS, missing: brain.AIO_VA_MISSING_ASSETS, photography_pass: brain.AIO_VA_PHOTOGRAPHY_PASS },
      components: brain.AIO_VA_COMPONENTS, ultra_wide: brain.AIO_VA_ULTRA_WIDE, permissions: brain.AIO_VA_PERMISSION_NOTES, comparison: brain.AIO_VA_COMPARISON, composer_handoff: brain.AIO_VA_COMPOSER_HANDOFF,
    }),
    'QUALITY_GATE.json': json(aioVisualAuthorityQualityGate()),
  };
}

if (process.argv[1] && /aio-office-visual-authority-export\.ts$/.test(process.argv[1])) {
  mkdirSync(AIO_VA_DOCS_DIR, { recursive: true });
  const files = buildAioVisualAuthorityExports();
  for (const [name, body] of Object.entries(files)) writeFileSync(`${AIO_VA_DOCS_DIR}/${name}`, body);
  console.log(`exported ${Object.keys(files).length} files to ${AIO_VA_DOCS_DIR}`);
}
