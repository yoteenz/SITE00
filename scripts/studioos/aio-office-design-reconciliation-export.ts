function at(id: string | null): string {
  if (!id) return '—';
  const n = iaNode(IA, id);
  if (!n) return id;
  const p = iaPath(IA, id);
  return n.shell_id === 'AIO_OFFICE' && p.length > 1 ? p.slice(1).join(' → ') : p.join(' → ');
}
const refLabel = (r: ContractRef) => {
  if (r.kind === 'NONE') return '—';
  if (r.kind === 'METRIC') { const m = C.metrics.find((x) => x.metric_id === r.id)!; return `metric ${m.label} (${m.classification}, ${m.state})`; }
  if (r.kind === 'ACTION') { const a = C.roots.flatMap((x) => x.actions).find((x) => x.action_id === r.id)!; return `action ${a.label} (${a.state})`; }
  if (r.kind === 'REGION') { const g = C.roots.flatMap((x) => x.regions).find((x) => x.region_id === r.id)!; return `region ${g.label}`; }
  return at(r.id);
};
