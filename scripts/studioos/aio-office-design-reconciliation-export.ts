/* ─────────────────────────────── 02–05 pages ─────────────────────────────── */

function pageMd(n: string, p: PageReconciliation, extra: string[] = []) {
  const name = short(p.root_id);
  const cov = coverage().filter((c) => c.root_id.startsWith(p.root_id));
  return [
    ...MD_HEAD(`${n} · ${name} reconciliation`),
    `**Drawn as:** “${screenOf(p.root_id).title_as_drawn}”  `,
    `**Contract:** ${C.roots.find((r) => r.root_id === p.root_id)!.purpose}`, '',
    '## A · What already works', '', ...bullets(p.works), '',
    '## B · What must be preserved', '', ...bullets(p.preserve), '',
    '## C · What is missing', '', ...bullets(p.missing), '',
    '## D · What is incorrect', '', ...bullets(p.incorrect), '',
    '## E · What needs visual refinement', '', ...bullets(p.refine), '',
    '## F · What needs your decision', '', ...bullets(p.founder_decisions.map((d) => `**${d}** — ${decision(d).title}: ${decision(d).question}`)), '',
    '## Coverage (computed from the drawing)', '',
    table(['Set', 'Required', 'Drawn', 'Missing', 'Drawn but not in the set'], cov.map((c) => [c.root_id === p.root_id ? name : `${name} → ${short(c.root_id)}`, String(c.required.length), String(c.drawn.length - c.extra.filter((x) => c.drawn.includes(x)).length), c.missing.map(short).join(' · ') || '—', c.extra.map((x) => (x.startsWith('AIO_OFFICE') ? short(x) : x)).join(' · ') || '—'])), '',
    '## Current versus required', '',
    table(['Topic', 'Current design', 'Required experience', 'Recommended change'], p.current_vs_required.map((r) => [r.topic, r.current, r.required, r.change])), '',
    '## The revised page (mobile reading order)', '',
    table(['Slot', 'Shows', 'How', 'Photo / icon'], p.proposed.map((s) => [s.label, refLabel(s.maps_to), s.treatment, s.asset ?? '—'])), '',
    ...extra,
  ].join('\n');
}

