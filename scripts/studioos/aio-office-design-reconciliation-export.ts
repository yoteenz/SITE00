const short = (id: string) => at(id).split(' → ').pop()!;

/* ─────────────────────────────── quality gate ─────────────────────────────── */

const yes = (b: boolean) => (b ? 'YES' : 'NO');
const eq = (a: readonly string[], b: readonly string[]) => a.length === b.length && a.every((v, i) => v === b[i]);

export function aioDesignReconciliationQualityGate(fileSha?: string) {
  const violations = validateDesignReconciliation(REC, C, IA);
  const els = REC.reference.screens.flatMap((s) => s.elements);
  const kept = els.filter((e) => e.verdict === 'KEEP' || e.verdict === 'REFINE' || e.verdict === 'ASSET_PASS').length;
  const removed = els.filter((e) => e.verdict === 'REMOVE').length;
  const proposedRefs = (root: string, kind: ContractRef['kind']) => pageOf(root).proposed.filter((s) => s.maps_to.kind === kind).map((s) => s.maps_to.id!);
  const home = C.roots[0];
  const homeProposed = proposedRefs(home.root_id, 'REGION');
  const lanes = proposedRefs('AIO_OFFICE.WORK', 'LANE');
  const entries = proposedRefs('AIO_OFFICE.MORE', 'MORE_ENTRY');
  const placement = brain.AIO_REPORT_DOMAIN_PLACEMENT.map((d) => `AIO_OFFICE.REPORTS.${d.domain}`);
  const figures = drawnFigures(REC, C);
  const unsupported = pageOf('AIO_OFFICE.REPORTS').proposed.filter((s) => s.maps_to.kind === 'METRIC').map((s) => ({ s, m: C.metrics.find((x) => x.metric_id === s.maps_to.id)! })).filter(({ m }) => m.classification === 'DERIVED_UNSUPPORTED' || m.classification === 'NOT_IMPLEMENTED');
  const logo = REC.assets.find((a) => a.asset_id === 'logo-header')!;
  const open = REC.decisions.filter((d) => d.status === 'OPEN');
  const plansDiffer = C.roots.every((r) => DESIGN_VIEWPORTS.every((vp) => REC.responsive.some((p) => p.root_id === r.root_id && p.viewport === vp)) && new Set(REC.responsive.filter((p) => p.root_id === r.root_id).map((p) => p.layout)).size === DESIGN_VIEWPORTS.length);
  const checks: { key: string; value: string; evidence: string }[] = [
    { key: 'ATTACHMENT_INSPECTED', value: yes(REC.reference.screens.length === 4 && els.length > 0 && (fileSha === undefined || fileSha === REC.reference.file.sha256)), evidence: `4 screens, ${els.length} drawn elements inventoried; reference sha256 ${REC.reference.file.sha256.slice(0, 12)}…` },
    { key: 'EXISTING_DESIGN_PRESERVED', value: yes(kept / els.length >= 0.7 && REC.pages.every((p) => p.preserve.length > 0)), evidence: `${kept} of ${els.length} drawn elements kept, refined or re-shot; ${removed} removed (the INTAKE lane tile and card)` },
    { key: 'PAGES_MATCH_CONTRACTS', value: yes(eq(homeProposed, home.regions.map((r) => r.region_id)) && eq(lanes, C.lanes.map((l) => l.lane_id)) && eq(placement, C.roots[2].regions.map((r) => r.region_id)) && eq([...entries].sort(), C.more_entries.map((e) => e.entry_id).sort())), evidence: 'proposed HOME = 8 regions in order · WORK = 12 lanes in order · REPORTS places all 10 domains · MORE = 11 entries' },
    { key: 'WORK_TWELVE_LANES', value: yes(lanes.length === 12 && !lanes.includes('AIO_OFFICE.INTAKE')), evidence: `proposed: ${lanes.map(short).join(' · ')}` },
    { key: 'MORE_ELEVEN_ENTRIES', value: yes(entries.length === 11), evidence: brain.AIO_MORE_PROPOSED_GROUPS.map((g) => `${g.group}: ${g.entries.length}`).join(' · ') },
    { key: 'HOME_NO_SERVICE_OWNERSHIP', value: yes(home.owns.length === 0 && pageOf(home.root_id).proposed.every((s) => s.maps_to.kind === 'ROOT' ? s.maps_to.id === home.root_id : s.maps_to.kind === 'REGION' && s.maps_to.id!.startsWith(home.root_id))), evidence: 'every proposed HOME slot is a HOME region that routes to its owner' },
    { key: 'REPORTS_NO_INVENTED_FIGURES', value: yes(figures.every((f) => !f.production_backed) && unsupported.every(({ s }) => /not connected/i.test(s.treatment))), evidence: `${figures.reduce((n, f) => n + f.figures.length, 0)} drawn figures, all design examples; ${unsupported.length} unsupported metric slot(s) drawn as honest states` },
    { key: 'FOUNDER_STAFF_VISIBILITY_DEFINED', value: yes(C.roots.every((r) => REC.roles.some((x) => x.root_id === r.root_id))), evidence: `${REC.roles.length} rows, each decided by a role or grant, never a name` },
    { key: 'RESPONSIVE_PLAN_INTENTIONAL', value: yes(plansDiffer), evidence: `${REC.responsive.length} plans: 4 roots × ${DESIGN_VIEWPORTS.join(' / ')}; each viewport has its own layout` },
    { key: 'BRANDING_PRESERVED', value: yes(logo.path === 'all-in-one-enterprises/public/migration/brand-lockup.png' && REC.assets.some((a) => a.asset_id === 'logo-global-dotted' && a.status === 'DO_NOT_USE')), evidence: 'header keeps the approved staff lockup; the dotted lockup and invented marks are kept out; no logo regenerated' },
    { key: 'PRODUCTION_CODE_CHANGED', value: 'NO', evidence: 'docs and Brain data only' },
    { key: 'IMAGES_GENERATED', value: '0', evidence: 'regeneration waits for founder approval' },
    { key: 'EXISTING_WORK_DISCARDED', value: 'NO', evidence: 'contracts, IA, IFTA and migration authorities untouched' },
    { key: 'FOUNDER_APPROVAL_REQUIRED', value: yes(open.length > 0 && open.every((d) => d.status === 'OPEN')), evidence: `${open.length} open decisions (${open.filter((d) => d.priority === 'BEFORE_REGENERATION').length} must be decided before regeneration)` },
  ];
  const ready = violations.length === 0 && checks.every((c) => c.value !== 'NO' || ['PRODUCTION_CODE_CHANGED', 'EXISTING_WORK_DISCARDED'].includes(c.key));
  checks.push({ key: 'READY_FOR_FOUNDER_REVIEW', value: yes(ready), evidence: `validator violations ${violations.length}` });
  return { ...head('AIO_DESIGN_RECONCILIATION_QUALITY_GATE'), next_gate: brain.AIO_DESIGN_RECON_NEXT_GATE, checks, coverage: coverage(), violations };
}

