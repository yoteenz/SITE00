import { mkdirSync, writeFileSync } from 'node:fs';
import { aio as brain } from '../../shared/studioos-experience-brain/index.js';

export const AIO_UO_DOCS_DIR = 'docs/aio/office-unified-experience';
const json = (v: unknown) => `${JSON.stringify(v, null, 2)}\n`;
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (h: string[], rows: string[][]) => [`| ${h.join(' | ')} |`, `|${h.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
const bullets = (xs: readonly string[]) => (xs.length ? xs.map((x) => `- ${x}`) : ['- —']);
const S = brain.AIO_UO_STATUS;
const word = (r: string) => r.replace(/_/g, ' ');
const MD_HEAD = (title: string) => [
  `# ${title}`, '',
  '> Generated by `scripts/studioos/aio-office-unified-experience-export.ts` from the Experience Brain. Do not edit by hand.', '',
  `**Sprint:** ${brain.AIO_UO_SPRINT} (${brain.AIO_UO_DATE})  `,
  `**Batch:** ${S.batch}  `,
  `**Office:** ${S.office}  `,
  `**Live app:** ${S.live_app}  `,
  `**Review:** ${brain.AIO_UO_REVIEW_LINK}  `,
  `**Next gate:** ${brain.AIO_UO_NEXT_GATE}`, '',
];
const tree = brain.AIO_UO_PAGE_TREE;
const treeRows = (root: string) => tree.filter((p) => p.root === root).map((p) => [p.family, `\`${p.route}\``, word(p.review), word(p.live), `${p.founder_only ? 'FOUNDER / GRANT ONLY. ' : ''}${p.note ?? ''}`]);

export function aioUnifiedExperienceQualityGate() {
  const problems = brain.validateUnifiedExperience();
  const count = (k: string) => tree.filter((p) => p.review === k).length;
  return {
    sprint: brain.AIO_UO_SPRINT,
    gate: {
      EVERY_IA_NODE_HAS_A_PAGE_FAMILY: problems.some((p) => /has no page/.test(p)) ? 'NO' : 'YES',
      FIVE_ROOTS: 'YES — HOME · INTAKE · WORK · REPORTS · MORE (FILING not restored)',
      TWELVE_LANES: brain.AIO_UO_LANES.length === 12 ? 'YES' : 'NO',
      TEN_REPORT_DOMAINS: brain.AIO_UO_REPORT_DOMAINS.length === 10 ? 'YES' : 'NO',
      ELEVEN_MORE_DESTINATIONS: brain.AIO_UO_MORE.length === 11 ? 'YES' : 'NO',
      REVIEW_QA_PASSED: brain.AIO_UO_QA.failures === 0 ? 'YES' : 'NO',
      APPROVED_SCREENS_REGENERATED: 'NO — approved roots, migration screens and IFTA authority shown unchanged',
      SAMPLE_DATA_ONLY: 'YES',
      FOUNDER_APPROVED: 'NO — AWAITING FOUNDER REVIEW',
      OFFICE_COMPLETE: 'NO — BATCH 1; continuation sprints recorded',
      LIVE_APP_COMPLETE: 'NO',
      SECURITY_GAPS_FIXED: 'NO — 12 OPEN; separate handoff',
      LIVE_IMPLEMENTATION_AUTHORIZED: 'NO',
    },
    counts: { page_families: tree.length, approved_root: count('APPROVED_ROOT'), approved_authority: count('APPROVED_AUTHORITY'), new_for_review: count('NEW_FOR_REVIEW'), honest_state: count('HONEST_STATE'), crawled_routes: brain.AIO_UO_QA.crawled_routes, journeys: brain.AIO_UO_JOURNEYS.length, screenshots: brain.AIO_UO_QA.screenshots, open_privacy_gaps: brain.AIO_UO_SECURITY_HANDOFF.length },
    problems,
    status: S,
    next_gate: brain.AIO_UO_NEXT_GATE,
  };
}

