export function buildAioUnifiedExperienceExports(): Record<string, string> {
  return {
    'README.md': readmeMd(),
    '01_INVENTORY.md': inventoryMd(),
    '02_FIVE_ROOT_PAGE_TREE.md': treeMd(),
    '03_SHARED_DESIGN_SYSTEM.md': designMd(),
    '04_INTAKE.md': intakeMd(),
    '05_WORK_LANES.md': workMd(),
    '06_REPORTS_AND_MORE.md': reportsMoreMd(),
    '07_ROLES_AND_CLIENT_CONTEXT.md': rolesMd(),
    '08_REVIEW_ENVIRONMENT_AND_VIEWPORTS.md': reviewMd(),
    '09_JOURNEYS_AND_QA.md': qaMd(),
    '10_COMPOSER_INTEGRATION_PLAN.md': composerMd(),
    '11_SECURITY_REPAIR_HANDOFF.md': securityMd(),
    '12_GAPS_AND_CONTINUATION.md': gapsMd(),
    '13_FOUNDER_WALKTHROUGH.md': walkMd(),
    'UNIFIED_EXPERIENCE.json': json({
      id: 'AIO_OFFICE_UNIFIED_EXPERIENCE', sprint: brain.AIO_UO_SPRINT, date: brain.AIO_UO_DATE, generated_by: 'scripts/studioos/aio-office-unified-experience-export.ts',
      source: ['shared/studioos-experience-brain/projects/aio/office-unified-experience.ts'], base: brain.AIO_UO_BASE,
      status: S, next_gate: brain.AIO_UO_NEXT_GATE, review_link: brain.AIO_UO_REVIEW_LINK, locations: brain.AIO_UO_LOCATIONS,
      inventory: brain.AIO_UO_INVENTORY, page_tree: tree, lanes: brain.AIO_UO_LANES, record_types: brain.AIO_UO_RECORD_TYPES, report_domains: brain.AIO_UO_REPORT_DOMAINS, more: brain.AIO_UO_MORE,
      components: brain.AIO_UO_COMPONENTS, roles: brain.AIO_UO_ROLES, client_context: brain.AIO_UO_CLIENT_CONTEXT, interactions: brain.AIO_UO_INTERACTIONS, viewports: brain.AIO_UO_VIEWPORTS, assets: brain.AIO_UO_ASSETS,
      journeys: brain.AIO_UO_JOURNEYS, qa: brain.AIO_UO_QA, composer_plan: brain.AIO_UO_COMPOSER_PLAN, security: { recheck: brain.AIO_UO_SECURITY_RECHECK, handoff: brain.AIO_UO_SECURITY_HANDOFF, grants: brain.AIO_UO_GRANT_ENFORCEMENT },
      product_gaps: brain.AIO_UO_PRODUCT_GAPS, continuation: brain.AIO_UO_CONTINUATION, walkthrough: brain.AIO_UO_WALKTHROUGH,
    }),
    'QUALITY_GATE.json': json(aioUnifiedExperienceQualityGate()),
  };
}

if (process.argv[1] && /aio-office-unified-experience-export\.ts$/.test(process.argv[1])) {
  mkdirSync(AIO_UO_DOCS_DIR, { recursive: true });
  const files = buildAioUnifiedExperienceExports();
  for (const [name, body] of Object.entries(files)) writeFileSync(`${AIO_UO_DOCS_DIR}/${name}`, body);
  console.log(`exported ${Object.keys(files).length} files to ${AIO_UO_DOCS_DIR}`);
}
