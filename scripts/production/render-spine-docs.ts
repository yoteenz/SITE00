/**
 * Renders the production-spine deliverables that are read straight from code or a run:
 *   06_JOB_AND_TAKE_STATE_MACHINE.md   from JOB_TRANSITIONS and TAKE_RULES
 *   12_S101_SH01_ZERO_SPEND_DRY_RUN.md from a fresh run of scripts/production/sh01DryRun.ts
 *
 *   npx tsx scripts/production/render-spine-docs.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { DISPATCHED_STATES, JOB_TRANSITIONS, TAKE_RULES } from '../../shared/site00-production-spine/machines.js';
import { JOB_STATES } from '../../shared/site00-production-spine/types.js';
import { runSh01DryRun } from './sh01DryRun.js';

export const SPINE_DOCS_DIR = 'docs/site00/production-spine-and-s101-alignment-v1';
const cell = (s: string) => s.replace(/\|/g, '\\|');
const table = (head: string[], rows: string[][]) => [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');

const NEEDS: Record<string, string> = {
  approvalId: 'the founder authorization record',
  ticketId: 'a dispatch ticket from the spend gate',
  operationId: 'the provider operation ID',
  error: 'the error, recorded on the job',
  assetId: 'the stored, hash-verified asset',
  takeId: 'the take (or NONE for an image job)',
  retryRequest: 'the founder’s reason for the retry',
};

export function renderStateMachineDoc(): string {
  const jobRows = JOB_STATES.flatMap((from) =>
    Object.entries(JOB_TRANSITIONS[from]).map(([to, rule]) => [from, to, rule!.who.join(', '), (rule!.needs ?? []).map((n) => NEEDS[n] ?? n).join('; ') || '—']),
  );
  const terminal = JOB_STATES.filter((s) => !Object.keys(JOB_TRANSITIONS[s]).length);
  const takeRows = Object.entries(TAKE_RULES).map(([a, r]) => [a.replace(/_/g, ' '), r.from.join(', '), r.who.join(', ')]);
  return `# 06 — Job and take state machines

> Generated by \`scripts/production/render-spine-docs.ts\` from \`shared/site00-production-spine/machines.ts\`. The tables are the code's own transition rules.

Two machines, kept apart (§17):

- **A job** records what was asked of a provider and what came back.
- **A take** records what the founder thinks of the result.

A provider succeeding never approves anything: it produces a take in READY_FOR_REVIEW.

## 1. Rules that hold everywhere

- Every transition names an actor, a time, a reason and its evidence, and is appended to the job's \`transitions\` list.
- A transition the table does not list is refused (ILLEGAL_TRANSITION).
- A transition made by the wrong role is refused (FORBIDDEN).
- A transition missing its evidence is refused (MISSING_EVIDENCE).
- **No automatic retry.** FAILED leaves only by a founder retry request. That request clears the old authorization, so the spend gate and a new founder authorization are needed again.
- **No automatic regeneration.** A REJECTED take stays rejected. Nothing in the spine creates a job in response.
- **Changed inputs void approval.** Changing a job's inputs, settings, prompt or requested outputs changes its input hash. An AUTHORIZED job goes back to AWAITING_APPROVAL.
- **Capture never resubmits.** Capturing again reads the provider's stored output. It does not call generation again.
- **Duplicates are idempotent.** Once a job is ${DISPATCHED_STATES.join(', ')}, a second dispatch returns the job as it is and sends nothing.

## 2. Job execution

Roles:

- FOUNDER is the founder.
- SYSTEM is the production runner.
- REVIEWER never moves a job.

${table(['From', 'To', 'Who', 'Needs'], jobRows)}

Terminal states: ${terminal.join(', ')}.

The normal path for a video job:

DRAFT → AWAITING_APPROVAL → AUTHORIZED → QUEUED → RUNNING → SUCCEEDED → ASSET_CAPTURE_PENDING → CAPTURED, then a take in READY_FOR_REVIEW.

An image (reference) job ends at CAPTURED with an asset and no take. The founder may then approve that asset as a shot reference.

## 3. Take review

${table(['Action', 'Allowed from', 'Who'], takeRows)}

- **One selection per shot.** Only one take per shot may be SELECTED_FOR_EDIT; another take must be deselected first (SELECTION_CONFLICT).
- **Deselect before withdrawing approval.** A selected take must be deselected before it can be held or rejected.
- **Every decision is a record.** Each one writes an immutable APPROVAL record, and the take keeps the list of them.
- **The stored copy is checked first.** APPROVE and SELECT FOR EDIT re-hash the stored copy and refuse if it changed (MEDIA_UNVERIFIED).
- **Withdrawing approval invalidates references.** When an approved take is held or rejected, every canonical continuity frame taken from it becomes INVALIDATED.

## 4. Where it is enforced and tested

- \`transitionJob\`, \`reviseJobInputs\` and \`decideTake\` are the only ways the runner changes state.
- \`tests/productionSpine.test.ts\` covers:
  - illegal moves, wrong roles and missing evidence;
  - the founder-only retry and its cleared authorization;
  - input changes voiding an authorization;
  - reviewer limits, single selection and final rejection;
  - capture failure without a provider call;
  - a rejected take starting nothing.
`;
}

export async function renderDryRunDoc(root = process.cwd()): Promise<string> {
  const r = await runSh01DryRun(root);
  fs.rmSync(r.workDir, { recursive: true, force: true });
  const rows = r.steps.map((s) => [String(s.n), s.title, s.pass ? 'PASS' : 'FAIL', s.evidence]);
  return `# 12 — S1-01-SH01 zero-spend dry run

> Generated by \`scripts/production/render-spine-docs.ts\` from a fresh run of \`scripts/production/sh01DryRun.ts\`. The same run is a test: \`tests/productionSpineApi.test.ts\`.

## Result

- **Steps:** ${r.steps.filter((s) => s.pass).length} of ${r.steps.length} pass.
- **Network calls during the run:** ${r.providerNetworkCalls}.
- **Real provider requests:** ${r.realProviderRequests}.
- **Credits spent:** ${r.creditsSpent}.
- **Live records unchanged:** ${r.liveRecordsUnchanged ? 'yes, every file hashes the same before and after' : 'NO'}.

**This is a simulation, not a live provider integration.**

- The fake provider stood in for OpenArt.
- The approvals in steps 8 to 18 are test fixtures, made in a temporary directory and marked TEST_FIXTURE.
- None of them is a founder decision.
- FD-S101-01, FD-S101-08 and FD-S101-11 are still OPEN in the live records.
- SH01 is still GENERATION_AUTHORIZATION_PENDING.

## How the run is staged

- **Steps 1 to 7: the live catalogue.**
  - It is read through the repository-JSON store, opened read-only.
  - It uses the real OpenArt agent-session route, which is disabled.
- **Steps 8 to 18: an isolated test environment** under the operating system's temp directory, outside the repository. It holds:
  - copies of the live setup records, marked as test data;
  - a test-only approval of every scene element;
  - a test founder who authorizes the 255-credit budget and the 175-credit video job;
  - a flat PNG standing in for a founder-supplied street photograph;
  - the fake provider, returning a locally generated test-pattern video (270 × 480, 24 fps, 5 s);
  - the local private media adapter.
- **The spine API runs in-process.** Steps 14 to 18 go through the same handler the app uses.
- **Steps 19 and 20 check the cost.** Every \`fetch\` during the run is counted, and the live record files are hashed before and after.

## Steps

${table(['#', 'Step', 'Result', 'Evidence'], rows)}

## What the run does not show

- **Live OpenArt execution.** The route is disabled, and no agent-session executor exists in the app.
- **A live private-storage transfer.** No bucket or credentials exist in this environment; the local adapter stood in.
- **Playback in a real browser.** The responsive check (deliverable 11) used a Chromium build without H.264 decoding.
- **Any founder decision.** All of them remain the founder's.
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const dir = path.join(process.cwd(), SPINE_DOCS_DIR);
  fs.writeFileSync(path.join(dir, '06_JOB_AND_TAKE_STATE_MACHINE.md'), renderStateMachineDoc());
  fs.writeFileSync(path.join(dir, '12_S101_SH01_ZERO_SPEND_DRY_RUN.md'), await renderDryRunDoc());
  console.log(`wrote ${SPINE_DOCS_DIR}/06 and /12`);
}
