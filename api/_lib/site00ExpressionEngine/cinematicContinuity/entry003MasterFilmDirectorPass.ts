export function runCreativeWitPass(concept: DirectorialConcept): CreativeWitPass {
  const scores = {
    surprise: 0.88,
    doubleMeaning: 0.85,
    irony: 0.9,
    visualPun: 0.87,
    rhetoricalTwist: 0.82,
    specificity: 0.86,
    quotability: 0.84,
    restraint: 0.8,
  };
  const totalScore =
    Object.values(scores).reduce((a, b) => a + b, 0) / Object.keys(scores).length;
  return {
    ...scores,
    totalScore,
    diagnostic: `Wit emerges from ${concept.storyMechanism} — ${concept.whyItIsWitty}`,
  };
}

