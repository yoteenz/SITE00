export function getTemplateById(id: string): EmailTemplateDefinition | undefined {
  return EMAIL_TEMPLATES.find((t) => t.id === id);
}

export const EMAIL_TEMPLATE_MAP = Object.fromEntries(EMAIL_TEMPLATES.map((t) => [t.id, t]));

export type EmailFamilyFilter = EmailFamily | 'all' | 'launch-qa';

export function filterTemplates(params: {
  family?: EmailFamilyFilter;
  status?: EmailDebugStatus | 'all';
  classification?: EmailClassification | 'all';
}): EmailTemplateDefinition[] {
  return EMAIL_TEMPLATES.filter((t) => {
    if (params.family && params.family !== 'all') {
      if (params.family === 'launch-qa') {
        if (t.family !== 'launch') return false;
      } else if (t.family !== params.family) {
        return false;
      }
    }
    if (params.status && params.status !== 'all' && t.debugStatus !== params.status) return false;
    if (params.classification && params.classification !== 'all' && t.classification !== params.classification) return false;
    return true;
  });
}

export function emailPackSummary(debugStatuses: Record<string, EmailDebugStatus>) {
  const total = EMAIL_TEMPLATES.length;
  const approved = EMAIL_TEMPLATES.filter((t) => (debugStatuses[t.id] ?? t.debugStatus) === 'approved').length;
  const needsReview = total - approved;
  const countFamily = (f: EmailFamily) => EMAIL_TEMPLATES.filter((t) => t.family === f).length;
  return {
    total,
    approved,
    needsReview,
    transactional: EMAIL_TEMPLATES.filter((t) => t.classification === 'transactional').length,
    production: EMAIL_TEMPLATES.filter((t) => t.classification === 'production' || t.classification === 'operational').length,
    marketing: EMAIL_TEMPLATES.filter((t) => t.classification === 'marketing').length,
    access: countFamily('access'),
    identity: countFamily('identity'),
    project: countFamily('project'),
    studio: countFamily('studio'),
    review: countFamily('review'),
    property: countFamily('property'),
    billing: countFamily('billing'),
    launch: countFamily('launch'),
    signal: countFamily('signal'),
  };
}
