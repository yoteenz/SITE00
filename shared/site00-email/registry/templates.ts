import type { EmailArchetype, EmailClassification, EmailDebugStatus, EmailFamily, EmailTemplateDefinition, EmailTemplateVars } from '../types.js';

function subject(text: string) {
  return (_v: EmailTemplateVars) => text;
}

function pre(text: string) {
  return (_v: EmailTemplateVars) => text;
}

function head(text: string | ((v: EmailTemplateVars) => string)) {
  return typeof text === 'string' ? (_v: EmailTemplateVars) => text : text;
}

function sub(text: string | ((v: EmailTemplateVars) => string)) {
  return typeof text === 'string' ? (_v: EmailTemplateVars) => text : text;
}

type Tpl = {
  num: number;
  id: string;
  name: string;
  family: EmailFamily;
  familyLabel: string;
  event: string;
  archetype: EmailArchetype;
  classification: EmailClassification;
  subject: (v: EmailTemplateVars) => string;
  preheader: (v: EmailTemplateVars) => string;
  headline: (v: EmailTemplateVars) => string;
  subheadline?: (v: EmailTemplateVars) => string;
  ctaLabel: string;
  debugStatus?: EmailDebugStatus;
  enabled?: boolean;
  notes?: string;
  defaultTheme?: 'light' | 'dark';
  varsForPreview?: Partial<EmailTemplateVars>;
};

function tpl(c: Tpl): EmailTemplateDefinition {
  return {
    ...c,
    debugStatus: c.debugStatus ?? 'needs-review',
    enabled: c.enabled ?? true,
  };
}

